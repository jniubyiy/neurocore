// src/compute_manager/executor.rs

//! Трейт исполнителя — абстракция над пулом потоков (CPU или GPU).
//!
//! Позволяет вышестоящему коду (`parallel.rs`, `graph/*`) не зависеть от
//! конкретной реализации пула: `ComputeThreadPool`, `ControlThreadPool`,
//! `GpuExecutor` — все реализуют `Executor`.
//!
//! Ключевые методы:
//! * [`Executor::execute_dyn`] — поставить задачу в пул.
//! * [`Executor::wait_all`] — синхронизация: дождаться завершения всех
//!   задач пула. Не блокирует воркеры внутри задач, в отличие от барьера.
//! * [`Executor::num_workers`] — количество воркеров в пуле.
//! * [`Executor::plan_chunks_assignment`] — получить раскладку задач по
//!   воркерам (внешний уровень — воркеры, внутренний — чанки этого воркера).
//! * [`Executor::report_execution_time`] — обратная связь: воркер сообщает
//!   время выполнения чанка. Метод имеет дефолтную реализацию-no-op;
//!   пулы со scheduler'ом переопределяют его, чтобы обучать mini-model
//!   для адаптивного распределения.

pub type ChunkAssignment = Vec<Vec<(usize, usize, usize)>>; // (start, size, end)

pub trait Executor: Send + Sync + 'static {
    /// Поставить задачу в пул на исполнение. Не блокирует вызывающий поток —
    /// задача будет подхвачена одним из воркеров пула.
    fn execute_dyn(&self, f: Box<dyn FnOnce() + Send>);

    /// Дождаться завершения всех активных задач пула.
    ///
    /// Реализации используют внутренний счётчик активных задач и не
    /// блокируют воркеры в середине выполнения — в отличие от `Barrier`,
    /// который блокирует воркер и не даёт ему взять следующую задачу.
    fn wait_all(&self);

    /// Количество воркеров в пуле.
    fn num_workers(&self) -> usize;

    /// Раскладка задач по воркерам.
    ///
    /// Возвращает вектор длиной `num_workers()`. Каждый элемент — список
    /// чанков, назначенных соответствующему воркеру. Формат чанка:
    /// `(start, size, end)`, где `start + size == end`.
    ///
    /// Воркер, получивший список из K чанков, обрабатывает их
    /// последовательно; распараллеливание между воркерами обеспечивается
    /// тем, что каждому воркеру назначен свой список.
    fn plan_chunks_assignment(&self, total_tasks: usize) -> ChunkAssignment;

    /// Обратная связь о времени выполнения задачи.
    ///
    /// Воркер вызывает этот метод после завершения обработки чанка
    /// с указанием номера воркера, размера задачи и длительности
    /// в наносекундах. Пул, имеющий scheduler, переопределяет метод и
    /// накапливает данные для обучения mini-model, которая в дальнейшем
    /// используется при построении `plan_chunks_assignment`.
    ///
    /// Дефолтная реализация — пустая (no-op). Это корректно для пулов
    /// без scheduler'а (`ControlThreadPool`, `GpuExecutor`).
    fn report_execution_time(
        &self,
        _worker_id: usize,
        _task_size: usize,
        _duration_ns: f64,
    ) {
        // no-op по умолчанию
    }

    /// Клонировать исполнителя, вернув трейт-объект. Позволяет хранить
    /// исполнителя в разных местах без зависимости от конкретного типа.
    fn clone_executor(&self) -> Box<dyn Executor>;
}