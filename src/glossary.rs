//! # Глоссарий NeuroCore

//! ## `mod models`
//! **Модельная структура** — это модуль, в котором собраны все модели,
//! используемые в проекте. Его задача — обеспечить взаимодействие между
//! различными моделями и предоставить единое пространство имён для их
//! определений. Внутри `mod models` каждая модель объявляется как отдельная
//! функция или структура.
//!
//! Пример:
//! ```
//! mod models {
//!     pub fn autoencoder() -> Vec<LayerDesc> { ... }
//!     pub fn classifier() -> Vec<LayerDesc> { ... }
//! }
//! ```

//! ## `pub fn`
//! **Модель** — это отдельная функция (обычно с модификатором `pub fn`),
//! которая описывает одну конкретную модель. Внутри такой функции
//! определяется последовательность слоёв (`LayerDesc`), составляющих модель.
//! Функция возвращает вектор `LayerDesc`, готовый для использования
//! в `TrainingPlan` или построении графа.
//!
//! Пример:
//! ```
//! pub fn autoencoder() -> Vec<LayerDesc> {
//!     vec![
//!         LayerDesc::new(LayerKind::Linear)
//!             .input(shape!(batch, A[4]))
//!             .output(shape!(batch, A[2])),
//!         LayerDesc::new(LayerKind::Sigmoid)
//!             .input(shape!(batch, A[2]))
//!             .output(shape!(batch, A[2])),
//!     ]
//! }
//! ```

//! ## `LayerDesc`
//! **Описание слоя** — структура, задающая параметры одного слоя модели.
//! Содержит тип слоя (`LayerKind`), входную и выходную форму (`Shape`),
//! а также дополнительные гиперпараметры (`extra`).
//! `LayerDesc` может быть началом, серединой или концом модели; в редких
//! случаях он же выступает в роли специального слоя (например,
//! `Splitter`/`Combiner`), который изменяет топологию графа.
//!
//! Пример:
//! ```
//! LayerDesc::new(LayerKind::Linear)
//!     .input(shape!(batch, A[6]))
//!     .output(shape!(batch, A[6]))
//! ```