// src/layers/adapter/trait.rs

//! Трейт [`GradientAdapter`] — контракт для per-layer коррекции градиента.
//!
//! Подключён в `mod.rs` через `#[path = "trait.rs"] mod adapter_trait;`
//! (модуль `trait` — зарезервированное слово Rust).

use super::AdapterContext;

/// Градиентный адаптер слоя.
///
/// # Роль в обучении (MIGRATION_PLAN.md §1.2, §2, инвариант I-1)
///
/// Шаг обучения проходит в порядке:
///
/// ```text
/// forward → loss → backward (raw)
///        → optimizer_modify_grads   (lr, momentum, adam, clip, decay)
///        → adapter_pass             ← ЭТОТ КОМПОНЕНТ
///        → optimizer_apply_update   (params -= grads)
/// ```
///
/// Адаптер получает **уже модифицированный оптимизатором** градиент
/// (после `modify_grads`) и имеет возможность его скорректировать до
/// того, как `apply_update` применит обновление к весам.
///
/// # Инварианты (MIGRATION_PLAN.md §2)
///
///   * **I-3:** адаптер трогает только `grad_params`. `grad_input`
///     (то, что уходит нижележащим слоям) адаптер **не может** искажать:
///     в [`AdapterContext`] нет доступа к `grad_input`, а сам `grad_input`
///     к моменту `adapter_pass` уже посчитан и живёт в отдельном буфере,
///     который адаптеру недоступен.
///
///   * **I-4:** адаптер — часть слоя, живёт в его папке
///     (`src/layers/<layer>/adapter/`).
///
///   * **I-5:** устройство адаптера совпадает с устройством слоя.
///     CPU-слой — CPU-адаптер, GPU-слой — GPU-адаптер. Никаких
///     автоматических GPU↔CPU roundtrip'ов: если адаптер хочет
///     работать на GPU, его шейдеры живут в `<layer>/adapter/gpu/`.
///
///   * **I-8:** адаптеры работают через `&self`, персистентное состояние —
///     внутри `Mutex`/`RwLock` (по образцу `BatchRenorm1d::state`).
///
///   * **I-9:** каждый слой имеет право на свою формулу, своё состояние,
///     свои гиперпараметры. Библиотека даёт инфраструктуру, но не диктует
///     математику.
///
///   * **I-10:** в первой итерации адаптер видит только слои своего
///     сегмента (границы `segment_params` / `segment_grads` в
///     [`AdapterContext`]). Cross-segment — вторая итерация.
///
/// # Область применения
///
/// Трейт специфицирует **только контракт**. Что именно делает `apply` —
/// определяет автор слоя. Типичные сценарии:
///
///   * коррекция масштаба градиента с учётом текущего режима слоя
///     (`LearnableMish` при малом λ, `Sigmoid` при насыщении);
///   * учёт специфики forward-состояния (например, разреженности маски
///     в `AdaptiveDropout`);
///   * нормировка на статистики слоя (`AdaptiveNormalization`).
pub trait GradientAdapter: Send + Sync + 'static {
    /// Применяет коррекцию к градиенту слоя.
    ///
    /// Вызывается один раз за шаг обучения, после `optimizer_modify_grads`
    /// и до `optimizer_apply_update`.
    ///
    /// Через [`AdapterContext`] адаптер получает:
    ///   * свой срез параметров (`ctx.read_own_params()`);
    ///   * свой срез градиентов (`ctx.read_own_grads()`,
    ///     `ctx.write_own_grads(...)`, `ctx.modify_own_grads(...)`);
    ///   * остальные срезы сегмента (для cross-layer математики в рамках I-10);
    ///   * размер батча;
    ///   * forward-state слоя (если слой его сохранил);
    ///   * своё состояние в `AdapterStateStore` (если оно есть).
    ///
    /// # Права и обязательства
    ///
    /// Адаптер **имеет право**:
    ///   * читать любые срезы `ctx.segment_params` и `ctx.segment_grads`
    ///     в пределах одного сегмента (I-10);
    ///   * модифицировать **свой** срез `ctx.segment_grads`
    ///     (градиент своего слоя);
    ///   * читать/писать **своё** состояние в `AdapterStateStore`
    ///     (если `ctx.own_state_slice` задан).
    ///
    /// Адаптер **не должен**:
    ///   * модифицировать срезы чужих слоёв сегмента
    ///     (кроме крайних случаев, требующих математического обоснования
    ///     внутри самого слоя — тогда это документируется в его README);
    ///   * искажать `grad_input` — такого доступа у него нет (I-3).
    ///
    /// # Детерминированность
    ///
    /// Адаптер вызывается **ровно один раз за шаг обучения**. Он не
    /// обязан быть идемпотентным, но должен быть детерминированным
    /// при одинаковом состоянии и контексте.
    ///
    /// # Паника
    ///
    /// Паника внутри `apply` — легальный способ сообщить о нарушении
    /// инварианта слоя. Так как это происходит в графе, паника приводит
    /// к аварийному завершению обучения.
    fn apply(&self, ctx: &AdapterContext<'_>);

    /// Человекочитаемое имя адаптера для диагностики.
    ///
    /// Используется в логах `NEUROCORE_DEBUG_ADAPTER=1` (Фаза 6 плана).
    /// По умолчанию возвращает `"adapter"`; конкретные адаптеры
    /// переопределяют на `"learnable_mish"`, `"learnable_softplus"` и т. п.
    #[inline]
    fn name(&self) -> &'static str {
        "adapter"
    }

    /// `true`, если адаптер имеет персистентное состояние.
    ///
    /// Нужно `bridge_v2` (Фаза 5), чтобы решить, выделять ли в
    /// `AdapterStateStore` буфер под этот адаптер.
    ///
    /// По умолчанию `false` (адаптер без состояния).
    #[inline]
    fn has_state(&self) -> bool {
        false
    }

    /// Размер состояния адаптера в элементах f32 на один обучаемый
    /// параметр слоя, если `has_state() == true`.
    ///
    /// Параллель `OptimizerCube::state_size_per_param`. По умолчанию `0`.
    #[inline]
    fn state_size_per_param(&self) -> usize {
        0
    }
}