//! Градиентный адаптер слоя `Linear` (MIGRATION_PLAN.md §7, Фаза 5).
//!
//! # Пилот
//!
//! Это первый адаптер в проекте. По решению администратора он **no-op**:
//! ничего не модифицирует, только валидирует [`AdapterContext`] через
//! `debug_assert`.
//!
//! Цель пилота — убедиться, что **среда адаптеров полностью прокинута**,
//! прежде чем писать первый адаптер с формулой:
//!
//!   * `GraphV2::adapter_pass` действительно вызывается;
//!   * `own_slice` / `all_slices` корректны и согласованы;
//!   * `segment_params` и `segment_grads` имеют одинаковую форму;
//!   * `forward_ctx` присутствует в момент `apply`
//!     (Фаза 4 сохраняет forward_cache до `optimizer_apply_update`);
//!   * `adapter_store` доступен (интеграция с `AdapterStateStore`);
//!   * `optimizer_applied == true` (инвариант I-1: adapter_pass
//!     вызывается строго между `modify_grads` и `apply_update`);
//!   * `batch > 0`.
//!
//! Все числовые результаты примеров должны быть **идентичны** baseline
//! (конец Фазы 4): адаптер не модифицирует градиент.
//!
//! # Почему именно `Linear`
//!
//! `Linear` — самый часто используемый слой в проекте (встречается
//! почти во всех примерах). Это даёт максимально широкое покрытие:
//! среда адаптеров проверяется на всех архитектурах, а не только на
//! одной специализированной. Если среда прокинута с ошибкой — она
//! проявится немедленно, а не «когда-нибудь на LearnableMish».
//!
//! # GPU-версия
//!
//! Заморожена до готовности инфраструктуры для адаптеров любых слоёв
//! (решение администратора). CPU-адаптер работает на CPU-сегментах;
//! для GPU-сегментов `adapter()` возвращает тот же no-op — среда
//! адаптеров проверяется без изменения чисел.

