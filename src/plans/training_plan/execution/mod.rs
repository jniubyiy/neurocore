//! Оркестрация обучения согласно `TrainingPlan`.
//!
//! Публичный API модуля:
//! * [`execute`] — запускает обучение в отдельном потоке с увеличенным
//!   стеком. Резолвится по фиче `v2`:
//!     * без фичи → [`execute_v1`] (старый оркестратор, `execute.rs`);
//!     * с фичей  → `execute_v2` (новый оркестратор, `execute_v2.rs`).
//! * [`execute_v1`] — старый оркестратор, доступный всегда, независимо
//!   от фичи. Используется для сравнения loss-кривых и отладки.
//! * [`TrainingResult`] — итоговый результат обучения.
//!
//! Внутренние подмодули:
//! * `types`     — `TrainingResult`;
//! * `overrides` — layer-aware канонические инициализации;
//! * `execute`   — v1-оркестраторы `execute` / `execute_inner`;
//! * `execute_v2`— v2-оркестратор (компилируется только с фичей `v2`).
//!
//! # Правила переключения
//!
//! * `cargo build` → `training_plan::execution::execute` = v1.
//! * `cargo build --features v2` → `training_plan::execution::execute` = v2.
//!
//! В обоих случаях оба оркестратора скомпилированы и доступны явно:
//! * `execute_v1` — всегда;
//! * `execute_v2` — только при фиче `v2`.
//!
//! `run_training!` вызывает `$crate::training_plan::execution::execute`,
//! поэтому все примеры автоматически идут либо через v1, либо через v2 —
//! в зависимости от фичи сборки.

mod types;
mod overrides;

// ---------------------------------------------------------------------------
// v1-оркестратор (`execute.rs`) — компилируется всегда.
//
// При сборке с `--features v2` `execute::execute` больше не вызывается
// через публичное имя `execute` — только через `execute_v1`. Чтобы не
// засорять вывод предупреждениями про «неиспользуемую» функцию и её
// внутренние хелперы, ставим allow(dead_code) на модуль.
//
// ВАЖНО: это атрибут на `mod execute`, а не правка самого `execute.rs`.
// Файл `execute.rs` остаётся неприкосновенным.
// ---------------------------------------------------------------------------
#[cfg_attr(feature = "v2", allow(dead_code))]
mod execute;

#[cfg(feature = "v2")]
mod execute_v2;

pub use types::TrainingResult;

// ---------------------------------------------------------------------------
// Публичный выбор оркестратора.
// ---------------------------------------------------------------------------

/// v1-оркестратор. Доступен всегда — независимо от фичи `v2`.
/// Полезен для сравнения поведения, отладочных прогонов и постепенной
/// миграции (можно запускать одни и те же данные через обе реализации).
pub use execute::execute as execute_v1;

/// v2-оркестратор. Доступен только при `--features v2`.
#[cfg(feature = "v2")]
pub use execute_v2::execute as execute_v2;

/// Основной оркестратор. Какой именно — определяется фичей сборки:
/// без `v2` — v1, с `v2` — v2. Символическое имя `execute`.
#[cfg(not(feature = "v2"))]
pub use execute::execute;

#[cfg(feature = "v2")]
pub use execute_v2::execute;